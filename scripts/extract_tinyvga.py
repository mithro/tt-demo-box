#!/usr/bin/env python3
"""Generate ``demobox/parts/tinyvga_data.py`` from the TinyVGA KiCad board.

Run (after ``make fetch``): uv run --no-project python scripts/extract_tinyvga.py

Same split as the submodule's tinytapeout/extract.py: every number comes out of
the ``.kicad_pcb``; the only judgement is ROLES (which designator plays which
role), so a rerun cannot quietly invent a dimension.

Plug frame (what the extracted boxes are in): viewed from the component side
with the Pmod edge at the bottom, as for a host board.  X runs along the Pmod
edge (0 at the PCB's left corner), Y = 0 at the PCB's host-side edge and
*negative Y is away from the host*, so the DE-15 sits at negative Y just like a
host's Pmod bodies overhang to negative Y.  KiCad (x, y) -> (X0 - y, x0 - x)
where (x0, ..) is the PCB bbox.  The Pmod pins stick out to positive Y (into the
host socket).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import demobox  # noqa: E402,F401
from tools import kicad_pcb  # noqa: E402

CLONE = ROOT / "tmp" / "src" / "tiny-vga"
PCB_PATH = "pcb/tiny-vga.kicad_pcb"
REPO_URL = "https://github.com/mole99/tiny-vga"
OUT = ROOT / "demobox" / "parts" / "tinyvga_data.py"

#: Judgement: which reference designator plays which role.
ROLES = {"header": ("J1", "PinHeader_2x06"), "de15": ("J2", "VGA-002")}


def extract(pcb: Path) -> dict:
    board = kicad_pcb.load(str(pcb))
    bx0, by0, bx1, by1 = board.outline_bbox()

    def to_box(bb):
        # KiCad (x, y) -> plug frame (by1 - y, bx0 - x); a box swaps its corners
        return tuple(round(v, 3) for v in
                     (by1 - bb[3], bx0 - bb[2], by1 - bb[1], bx0 - bb[0]))

    out = {"thickness": board.thickness, "pcb": to_box((bx0, by0, bx1, by1))}
    for name, (ref, lib) in ROLES.items():
        fp = board.by_reference(ref)[0]
        assert lib in fp.library_id, f"{ref} is {fp.library_id}, expected {lib}"
        out[name] = to_box(fp.bbox("courtyard"))
    return out


def commit_of(clone: Path) -> str:
    return subprocess.run(["git", "-C", str(clone), "rev-parse", "HEAD"], check=True,
                          capture_output=True, text=True).stdout.strip()


def render(data: dict, commit: str) -> str:
    return f'''"""GENERATED by scripts/extract_tinyvga.py from the TinyVGA KiCad board; do not edit.

Plug frame, boxes as (x0, y0, x1, y1) in mm: X along the Pmod edge, Y = 0 at the
PCB's host-side edge, negative Y away from the host (see the extractor).
"""

from tools.schema import Source

COMMIT = {commit!r}

SOURCES = (
    Source(label="TinyVGA KiCad board",
           ref="{REPO_URL}  {PCB_PATH} @ {commit}",
           note="PCB = Edge.Cuts bbox; header = J1 courtyard; de15 = J2 (VGA-002) courtyard"),
)

EXTRACTED = {data!r}
'''


def main() -> None:
    if not CLONE.exists():
        raise SystemExit("tmp/src/tiny-vga is missing: run make fetch")
    data = extract(CLONE / PCB_PATH)
    OUT.write_text(render(data, commit_of(CLONE)))
    print(f"wrote {OUT}")
    print(data)


if __name__ == "__main__":
    main()
